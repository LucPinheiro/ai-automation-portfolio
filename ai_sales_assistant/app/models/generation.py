from datetime import UTC, datetime
from decimal import Decimal
from enum import StrEnum

from sqlalchemy import CheckConstraint, Enum, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.constants import (
    EMAIL_MAX_LENGTH,
    COMPANY_MAX_LENGTH,
    CUSTOMER_MAX_LENGTH,
    INDUSTRY_MAX_LENGTH,
    PRODUCT_OR_SERVICE_MAX_LENGTH,
    SALESPERSON_COMPANY_MAX_LENGTH,
    SALESPERSON_MAX_LENGTH,
)
from app.core.enums import ContentType, Language, Tone
from app.database.base import Base
from app.services import pricing
from app.database.types import UTCDateTime


def _enum_column_type(enum_class: type[StrEnum], length: int) -> Enum:
    # Stored as plain strings holding the enum *values* (e.g. "commercial_email"),
    # without native DB enums or CHECK constraints, so new values need no migration
    # and SQLite/PostgreSQL behave the same.
    return Enum(
        enum_class,
        native_enum=False,
        create_constraint=False,
        length=length,
        values_callable=lambda members: [member.value for member in members],
        validate_strings=True,
    )


def _utc_now() -> datetime:
    return datetime.now(UTC)


class Generation(Base):
    """A piece of commercial content generated by the AI, with the input it was based on."""

    __tablename__ = "generations"
    __table_args__ = (
        CheckConstraint("price_cents > 0", name="price_positive"),
        CheckConstraint("discount_basis_points BETWEEN 0 AND 10000", name="discount_in_range"),
        CheckConstraint(
            "discount_basis_points IS NULL OR price_cents IS NOT NULL", name="discount_requires_price"
        ),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    # Owner. Nullable only for generations created before user accounts existed: those rows are
    # invisible to every user until assigned with `python -m app.cli assign-orphan-generations`.
    user_id: Mapped[int | None] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    content_type: Mapped[ContentType] = mapped_column(_enum_column_type(ContentType, 32), index=True)

    customer: Mapped[str] = mapped_column(String(CUSTOMER_MAX_LENGTH))
    # Optional contact email of the customer: pre-fills the "To" of the share-by-email button.
    # Never sent to the AI provider.
    customer_email: Mapped[str | None] = mapped_column(String(EMAIL_MAX_LENGTH))
    company: Mapped[str] = mapped_column(String(COMPANY_MAX_LENGTH))
    industry: Mapped[str] = mapped_column(String(INDUSTRY_MAX_LENGTH))
    product_or_service: Mapped[str] = mapped_column(String(PRODUCT_OR_SERVICE_MAX_LENGTH))
    customer_needs: Mapped[str] = mapped_column(Text)
    # Sender of the communication (optional; empty for generations created before it existed).
    salesperson: Mapped[str | None] = mapped_column(String(SALESPERSON_MAX_LENGTH))
    salesperson_company: Mapped[str | None] = mapped_column(String(SALESPERSON_COMPANY_MAX_LENGTH))
    # Pricing input, stored as exact integers (cents and hundredths of a percent). The discount
    # amount and final price are derived with app.services.pricing and never stored.
    price_cents: Mapped[int | None] = mapped_column(Integer)
    discount_basis_points: Mapped[int | None] = mapped_column(Integer)
    language: Mapped[Language] = mapped_column(_enum_column_type(Language, 8))
    tone: Mapped[Tone] = mapped_column(_enum_column_type(Tone, 32))

    generated_content: Mapped[str] = mapped_column(Text)
    ai_provider: Mapped[str] = mapped_column(String(32))
    ai_model: Mapped[str] = mapped_column(String(64))
    prompt_tokens: Mapped[int | None] = mapped_column(Integer)
    completion_tokens: Mapped[int | None] = mapped_column(Integer)

    created_at: Mapped[datetime] = mapped_column(UTCDateTime(), default=_utc_now, index=True)

    @property
    def price(self) -> Decimal | None:
        return None if self.price_cents is None else pricing.from_cents(self.price_cents)

    @price.setter
    def price(self, value: Decimal | None) -> None:
        self.price_cents = None if value is None else pricing.to_cents(value)

    @property
    def discount_percent(self) -> Decimal | None:
        return None if self.discount_basis_points is None else pricing.from_basis_points(self.discount_basis_points)

    @discount_percent.setter
    def discount_percent(self, value: Decimal | None) -> None:
        self.discount_basis_points = None if value is None else pricing.to_basis_points(value)

    def __repr__(self) -> str:
        return f"Generation(id={self.id!r}, content_type={self.content_type!r})"
